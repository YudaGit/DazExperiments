// Color palette switch (default: OKLab to match original encoding study)
var useOkLabPalette = true;

function okLabToLinSRGB(L, a, b) {
  var l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  var m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  var s_ = L - 0.0894841775 * a - 1.2914855480 * b;

  var l3 = l_ * l_ * l_;
  var m3 = m_ * m_ * m_;
  var s3 = s_ * s_ * s_;

  var r =  4.0767416621 * l3 + -3.3077115913 * m3 +  0.2309699292 * s3;
  var g = -1.2684380046 * l3 +  2.6097574011 * m3 + -0.3413193965 * s3;
  var b2 = -0.0041960863 * l3 + -0.7034186147 * m3 +  1.7076147010 * s3;

  return [r, g, b2];
}

function linToSrgbChannel(val) {
  var v = Math.max(0, Math.min(1, val));
  if (v <= 0.0031308) {
    return 12.92 * v;
  }
  return 1.055 * Math.pow(v, 1 / 2.4) - 0.055;
}

function buildOkLabPalette() {
  var L = 0.85;
  var radius = 0.23;
  var palette = [];
  for (let i = 0; i < 360; i++) {
    var angle = 2 * Math.PI * i / 360;
    var a = radius * Math.cos(angle);
    var b = radius * Math.sin(angle);
    var lin = okLabToLinSRGB(L, a, b);
    var r = linToSrgbChannel(lin[0]);
    var g = linToSrgbChannel(lin[1]);
    var bch = linToSrgbChannel(lin[2]);
    palette.push([r * 255, g * 255, bch * 255]);
  }
  return palette;
}

// CIE L*a*b* (D65) to sRGB. L in [0,100], a,b unbounded. Returns [R,G,B] 0-255.
function cieLabToSrgb(L, a, b) {
  var Xn = 0.95047, Yn = 1, Zn = 1.08883;
  var delta = 6 / 29;
  var fy = (L + 16) / 116;
  var fx = a / 500 + fy;
  var fz = fy - b / 200;
  function f(t) {
    return t > delta ? t * t * t : (t - 4 / 29) * (3 * delta * delta);
  }
  var X = Xn * f(fx);
  var Y = Yn * f(fy);
  var Z = Zn * f(fz);
  var r =  3.2404542 * X - 1.5371385 * Y - 0.4985314 * Z;
  var g = -0.9692660 * X + 1.8760108 * Y + 0.0415560 * Z;
  var blin = 0.0556434 * X - 0.2040259 * Y + 1.0572252 * Z;
  r = Math.max(0, Math.min(1, linToSrgbChannel(r)));
  g = Math.max(0, Math.min(1, linToSrgbChannel(g)));
  blin = Math.max(0, Math.min(1, linToSrgbChannel(blin)));
  return [r * 255, g * 255, blin * 255];
}

// CIE LAB color wheel (Exp1_Encoding_1.m: useCIE_LABcolorwheel branch). L=65, a=20, b=0, radius=70, 360 spokes.
function buildCieLabPalette() {
  var L = 65, aCenter = 20, bCenter = 0, radius = 70;
  var palette = [];
  for (var i = 0; i < 360; i++) {
    var angle = 2 * Math.PI * i / 360;
    var a = aCenter + radius * Math.cos(angle);
    var b = bCenter + radius * Math.sin(angle);
    palette.push(cieLabToSrgb(L, a, b));
  }
  return palette;
}


function SelectColorPatches( N ){
  // Select Patch Colors from among 12 pseudo random locations
  var colorAngles = []
  var Colors = []
  while (colorAngles.length < N){
    var rng = Math.floor(Math.random() * 12 )
    if (colorAngles.includes(rng * 360/12) == false){
      colorAngles.push(rng * 360/12)
    }
  }
  // Add within-sector variance to each sector start location.
  for (var ii = 0; ii < N; ii++){
    colorAngles[ii] += Math.floor(Math.random() * ((360/12 - 1) - 1))
    Colors.push( highRGBs[ colorAngles[ii] ] )
  }
  
  // Select Patch Angles
  var patchAngles = []
  var rng = Math.floor(Math.random() * 360/N )
  
  for (var ii = 0; ii < N; ii++){
    patchAngles.push(rng + (360/N - 1) * ii)
    if (patchAngles[ii] > 359){
      patchAngles[ii] -= 359
    }
  }
  return [Colors, colorAngles, patchAngles]
}

function selectRedundantColorPatches( Nitems , Ncolors ){
  var colorAngles = []
  var Colors = []
  var tempAngles = []
  // Select six spokes of the color wheel
  while (colorAngles.length < Ncolors){
    var newangle = Math.floor(Math.random() * 6 ) * 360/6
    if (!colorAngles.includes(newangle)){
      colorAngles.push(newangle)
    }
  }

  // Add uniform random distance to each spoke
  //  ensuring a gap of +- 15 degrees between each color.
  //  This ensures redundancy isn't accidental.
  function UniqueAndValid(newAngle, existingAngles) {
    return existingAngles.every(function(angle) {
      return Math.abs(angle - newAngle) >= 15;
    });
  }

  var ii = 0
  while (Colors.length < Ncolors){
    var proposedAngle = colorAngles[ii] + Math.floor(Math.random() * ((360/6 - 1) - 1))
    if (UniqueAndValid(proposedAngle, tempAngles)){
      tempAngles.push( proposedAngle)
      Colors.push( highRGBs[proposedAngle])
      ii = ii + 1
    }
  }
  // If redundancy is necessary, pick a random color and add it
  //  to the vector repeatedly until the vector length = Nitems
  if (Colors.length < Nitems){
    var RandIdx = Math.floor(Math.random() * Colors.length);
    while (Colors.length < Nitems){
      Colors.push(Colors[RandIdx])
      tempAngles.push(tempAngles[RandIdx])
    }
  }
  colorAngles = tempAngles
  

  // Select Nitem Patch Angles and randomize their
  //  order so redundant colors are not always
  //  aligned side-by-side.
  var patchAngles = []
  var rng = Math.floor(Math.random() * 360/Nitems )
  for (var ii = 0; ii < Nitems; ii++){
    patchAngles.push(rng + (360/Nitems - 1) * ii)
    if (patchAngles[ii] > 359){
      patchAngles[ii] -= 359
    }
  }

  function shuffleVect(array) {
    for (let i = array.length - 1; i > 0; i--) {
      let j = Math.floor(Math.random() * (i + 1)); // random index from 0 to i
      [array[i], array[j]] = [array[j], array[i]]; // swap elements
    }
  }

  shuffleVect(patchAngles)

  return [Colors, colorAngles, patchAngles]
}

function shuffleRedundancy(itemVect, colorVect, redundancyVect, trialVect){
  let I = []
  let C = []
  let R = []
  for (let ii = 0; ii < trialVect.length; ii++){
    I.push(...Array(trialVect[ii]).fill(itemVect[ii]).flat())
    C.push(...Array(trialVect[ii]).fill(colorVect[ii]).flat())
    R.push(...Array(trialVect[ii]).fill(redundancyVect[ii]).flat())
  }

  let idx = I.length; 
  let order = range(0, I.length-1)
  while (idx != 0){
    let ridx = Math.floor(Math.random() * idx);
    idx--;
    [order[idx], order[ridx]] = [order[ridx], order[idx]];
  }

  var shuffleI = [];
  var shuffleC = [];
  var shuffleR = [];
  for (let ii = 0; ii < order.length; ii++){
    shuffleI[ii] = I[ order[ii] ]
    shuffleC[ii] = C[ order[ii] ]
    shuffleR[ii] = R[ order[ii] ]
  }
  return [shuffleI, shuffleC, shuffleR]
}


function shuffle(a1, a2, a3, Multiplier){
  // a: array 1, 2, and 3 to shuffle.
  let A1 = []
  let A2 = []
  let A3 = []
  for (let a1i = 0; a1i < a1.length; a1i++){
    for (let a2i = 0; a2i < a2.length; a2i++){
      for (let a3i = 0; a3i < a3.length; a3i++){
        A1.push( a1[a1i] )
        A2.push( a2[a2i] )
        A3.push( a3[a3i] )
      }
    }
  }
  // Apply Multipler
  A1 = Array(Multiplier).fill(A1).flat()
  A2 = Array(Multiplier).fill(A2).flat()
  A3 = Array(Multiplier).fill(A3).flat()

  let idx = A1.length; 
  let order = range(0, A1.length-1)
  while (idx != 0){
    let ridx = Math.floor(Math.random() * idx);
    idx--;
    [order[idx], order[ridx]] = [order[ridx], order[idx]];
  }

  var shuffleA1 = [];
  var shuffleA2 = [];
  var shuffleA3 = [];
  for (let ii = 0; ii < order.length; ii++){
    shuffleA1[ii] = A1[ order[ii] ]
    shuffleA2[ii] = A2[ order[ii] ]
    shuffleA3[ii] = A3[ order[ii] ]
  }
  return [shuffleA1, shuffleA2, shuffleA3]
}

function range(start, end) {
  return Array(end - start + 1).fill().map((_, idx) => start + idx)
}
  

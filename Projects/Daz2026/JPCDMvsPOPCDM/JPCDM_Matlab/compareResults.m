k = load('jp_fit_freeKappa_groupedVnorm_results.mat');
p = load('jp_fit_freePsi_groupedVnorm_results.mat');

nSub = numel(k.fitResultKappaCond);

rows = table();

for i = 1:nSub
    uid = k.fitResultKappaCond(i).uid;

    nObs = sum(d.uid == uid);
    nPar9k = numel(k.fitResultKappaCond(i).Qfit);
    nPar9p = numel(p.fitResultPsiCond(i).Qfit);

    nll9k = k.fitResultKappaCond(i).bestNLL;
    nll9p = p.fitResultPsiCond(i).bestNLL;

    AIC9k = 2*nPar9k + 2*nll9k;
    AIC9p = 2*nPar9p + 2*nll9p;

    BIC9k = nPar9k*log(nObs) + 2*nll9k;
    BIC9p = nPar9p*log(nObs) + 2*nll9p;

    rows = [rows; table( ...
        uid, ...
        nObs, ...
        nll9k, nll9p, ...
        AIC9k, AIC9p, ...
        BIC9k, BIC9p, ...
        nll9p - nll9k, ...
        AIC9p - AIC9k, ...
        BIC9p - BIC9k, ...
        'VariableNames', {'uid', 'nObs', ...
        'NLL_9k3v', 'NLL_9p3v', ...
        'AIC_9k3v', 'AIC_9p3v', ...
        'BIC_9k3v', 'BIC_9p3v', ...
        'dNLL_9p_minus_9k', ...
        'dAIC_9p_minus_9k', ...
        'dBIC_9p_minus_9k'})]; %#ok<AGROW>
end

disp(rows);
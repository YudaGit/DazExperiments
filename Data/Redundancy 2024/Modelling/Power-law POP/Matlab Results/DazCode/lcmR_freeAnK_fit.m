function [theta, ptheta] = guplcm(P, n)
    a = P(1);
    kappa = P(2);
    theta = linspace(-pi, pi, n); % will wrap around
    utheta = a * exp(kappa * cos(theta)) / (2 * pi); % Tuning function
    ptheta = exp(utheta) / sum(exp(utheta));
    h = theta(2) - theta(1);
    ptheta = ptheta / h;
end

